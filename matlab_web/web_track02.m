function data = web_track02()
% WEB_TRACK02 Read geometry through the ORIGINAL RaceTrack class, without editing it.
root = fileparts(fileparts(mfilename('fullpath')));
original = fullfile(root, 'matlab_original', 'GP_MPC_Desktop_V3');
addpath(fullfile(original, 'classes'));
[segments, p0, h0, width] = RaceTrack.loadTrack_02();
track = RaceTrack(segments, p0, h0, width);
sourcefile = fullfile(original, 'classes', 'RaceTrack.m');
data = struct('schema', 'original-track-v1', 'id', 'track02-original-v1', ...
    'name', 'Original Track02 (MATLAB native)', 'points', track.track_c', ...
    'left', track.track_l', 'right', track.track_r', 'heading', track.psi_c(:)', ...
    'matlab_dist', track.dist(:)', 'width', width, 'length', max(track.dist), ...
    'closed', false, 'initial_state', [5, 0, 0, 10, 0, 0]);
data.source = struct('kind', 'matlab-native-export', 'method', ...
    'RaceTrack.loadTrack_02 + original RaceTrack constructor', ...
    'sha256', web_sha256(sourcefile), 'units', 'metres, radians, seconds');
end
